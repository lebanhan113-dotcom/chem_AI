import assert from 'node:assert/strict';
import {gradeOne,gradeAttempt,validateQuestion,publicQuestion} from '../supabase/functions/exam-api/scoring.mjs';
function base(type,answer){return {id:type,position:1,section:'I',type,body:'Dữ liệu thật kiểm thử',options:[],statements:[],points:1,answer,approved:true,issues:[],grading:{}}}
const mc={...base('mcq','C'),options:[{id:'A',text:'một'},{id:'C',text:'hai'}]};
assert.equal(gradeOne(mc,'C').score,1);assert.equal(gradeOne(mc,'A').score,0);
const tf={...base('tf',{a:true,b:false,c:true,d:false}),statements:'abcd'.split('').map(id=>({id,text:id})),grading:{mode:'per_statement'}};
assert.equal(gradeOne(tf,{a:true,b:false,c:false,d:true}).score,.5);
const tf2={...tf,grading:{mode:'score_by_correct_count',scores:{0:0,1:0.1,2:0.25,3:0.5,4:1}}};
assert.equal(gradeOne(tf2,{a:true,b:false,c:false,d:true}).score,.25);
const short={...base('short','1,25'),grading:{tolerance:0.01}};
assert.equal(gradeOne(short,'1.252').score,1);
assert.equal(gradeOne(short,'1.4').score,0);
const essay={...base('essay',null),rubric:'Chấm chi tiết'};
const res=gradeAttempt([mc,tf2,short,essay],{mcq:'C',tf:{a:true,b:false,c:false,d:true},short:'1,25'});
assert.equal(res.pending,1);assert.equal(res.final_score,null);
assert.equal(res.auto_score,2.25);
assert.equal(publicQuestion(mc).answer,undefined);
assert.equal(publicQuestion(tf).grading,undefined);
assert.deepEqual(validateQuestion(essay),[]);
assert.ok(validateQuestion({...mc,approved:false}).length);
console.log('OK scoring: MCQ, true/false, short, essay pending, no key leakage, validation');
