const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const Engine=require('../assets/engine.js');
const context={window:{}};vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'../assets/bank.js'),'utf8'),context);
const data=context.window.CHEM_BANK;
const questions=data.questions;
assert.equal(questions.length,51,'51 sample questions');
for(const q of questions){assert.equal(Engine.validateQuestion(q),null,`Schema failed ${q.id}`);assert.ok(q.explanation&&q.grade);}
const forms=['mcq','tf','short','essay'];assert.deepEqual(forms.map(t=>questions.filter(q=>q.type===t).length),[36,6,6,3]);
const sample=questions.find(q=>q.type==='mcq'&&q.grade===11);
assert.equal(Engine.evaluate(sample,String(sample.correct)).earned,1);
const distractor=Object.keys(sample.distractors)[0];
assert.equal(Engine.evaluate(sample,distractor).correct,false);
assert.equal(Engine.evaluate(sample,distractor).diagnostics[0].status,'suspected');
assert.equal(Engine.evaluate(sample,'').answered,false);
const tf=questions.find(q=>q.type==='tf');
assert.equal(Engine.evaluate(tf,tf.correct.map(v=>v?'T':'F')).earned,1);
assert.equal(Engine.evaluate(tf,['','','','']).earned,0);
assert.equal(Engine.evaluate(tf,['T','T','T','T']).max,1);
const short=questions.find(q=>q.type==='short');
assert.equal(Engine.evaluate(short,String(short.correct).replace('.',',')).earned,1);
assert.equal(Engine.evaluate(short,'xx').earned,0);
const essay=questions.find(q=>q.type==='essay');
assert.equal(Engine.evaluate(essay,'bài tự luận có lập luận').pending,true);
const result=Engine.gradeAttempt([sample,tf,short,essay],{[sample.id]:String(sample.correct),[tf.id]:tf.correct.map(v=>v?'T':'F'),[short.id]:String(short.correct),[essay.id]:'Bài làm'});
assert.equal(result.pendingCount,1);assert.equal(result.score,7.5);assert.equal(result.autoScore,10);
let a={...result};a.results[3].pending=false;a.results[3].earned=0.5;Engine.rescore(a);assert.equal(a.pendingCount,0);assert.equal(a.score,8.75);
const attempts=[{studentId:'hs-01',createdAt:'2026-01-01',questions:[sample,tf,short],results:[Engine.evaluate(sample,distractor),Engine.evaluate(tf,['T','F','F','T']),Engine.evaluate(short,'99')]}];
const plan=Engine.plan(attempts,questions,'hs-01',11);assert.ok(plan.items.length>=1&&plan.items.length<=5);assert.ok(plan.hasHistory);
const mastery=Engine.mastery(attempts,'hs-01');assert.ok(mastery.every(x=>x.percent>=0&&x.percent<=100));
console.log(`PASS: ${questions.length} items, grading (all types), diagnostic hypotheses, manual essay review, personalized plan, mastery`);
